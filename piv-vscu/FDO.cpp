NTSTATUS FDO::PnP(PDEVICE_OBJECT DeviceObject, PIRP Irp, PIO_STACK_LOCATION IrpSp)
{
	ULONG_PTR Information = Irp->IoStatus.Information;

	Irp->IoStatus.Information = 0;

	DbgPrint("FDO::PnP(%s) [%p]\n", PnPMinorFunctionString(IrpSp->MinorFunction), Information);

	//DumpStack();

	NTSTATUS status = STATUS_NOT_IMPLEMENTED;

	PDEVICE_RELATIONS p = 0;

	LONG NumPDOs;

	PIO_STACK_LOCATION nextIrpSp;

	switch(IrpSp->MinorFunction)
	{
	case IRP_MN_REMOVE_DEVICE:

		status = STATUS_NO_SUCH_DEVICE;

		if (ExAcquireRundownProtection(this))
		{
			DbgPrint("IRP_MN_REMOVE_DEVICE(%p)\n", Ptr);

			IoSkipCurrentIrpStackLocation(Irp);
			status = IofCallDriver(_nextDeviceObject, Irp);
			ExReleaseRundownProtection(this);
			ExWaitForRundownProtectionRelease(this);
			DbgPrint("-= delete FDO:%p =-\n", DeviceObject);

			IoDetachDevice(_nextDeviceObject);
			IoDeleteDevice(DeviceObject);
		}

		return status;

	default:
		Irp->IoStatus.Information = Information;
		if (!ExAcquireRundownProtection(this))
		{
			status = STATUS_NO_SUCH_DEVICE;
			break;
		}
		*(nextIrpSp = IrpSp - 1) = *IrpSp;
		nextIrpSp->Control = SL_INVOKE_ON_SUCCESS|SL_INVOKE_ON_ERROR|SL_INVOKE_ON_CANCEL;
		nextIrpSp->Context = this;
		nextIrpSp->CompletionRoutine = (PIO_COMPLETION_ROUTINE)OnComplete;
		return IofCallDriver(_nextDeviceObject, Irp);

	case IRP_MN_QUERY_DEVICE_RELATIONS:

		DbgPrint("\r\nFDO:QueryDeviceRelations(%s)", QueryDeviceRelationsString(IrpSp->Parameters.QueryDeviceRelations.Type));

		if (BusRelations != IrpSp->Parameters.QueryDeviceRelations.Type) 
		{
			status = Irp->IoStatus.Status;
			Irp->IoStatus.Information = Information;
			break;
		}

		free((PDEVICE_RELATIONS)Information);

		AcquirePushLockExclusive(&_lock);//+++++++++++++

		NumPDOs = 0;

		PLIST_ENTRY head = this, entry = head;

		while ((entry = entry->Flink) != head)
		{
			PDO* pdo = static_cast<PDO*>(entry);

			if (pdo->_RemovePending)
			{
				pdo->_Enumerated = FALSE;
				RemoveEntryList(entry);
				ObfDereferenceObject(pdo->_DeviceObject);
				DbgPrint("FDO unlink PDO<%p>\n", pdo);
			}
			else
			{
				NumPDOs++;
			}
		}

		status = STATUS_INSUFFICIENT_RESOURCES;

		if (p = (PDEVICE_RELATIONS)ExAllocatePool(PagedPool, FIELD_OFFSET(DEVICE_RELATIONS, Objects[NumPDOs])))
		{
			PDEVICE_OBJECT *pDeviceObject = p->Objects;

			while ((entry = entry->Flink) != head)
			{
				DeviceObject = static_cast<PDO*>(entry)->_DeviceObject;
				*pDeviceObject++ = DeviceObject;
				ObfReferenceObject(DeviceObject);
			}

			Irp->IoStatus.Information = (ULONG_PTR)p;
			p->Count = NumPDOs;
			status = STATUS_SUCCESS;
		}

		ReleasePushLockExclusive(&_lock);//----------------

		break;
	}

	Irp->IoStatus.Status = status;
	IofCompleteRequest(Irp, IO_NO_INCREMENT);
	return status;
}

