// FileObject->FsContext -> PDO

NTSTATUS FDO::Cleanup(PDEVICE_OBJECT , PIRP , PIO_STACK_LOCATION IrpSp)
{
	DbgPrint("FDO::Cleanup(%p)\n", IrpSp->FileObject);

	if (PFILE_OBJECT FileObject = IrpSp->FileObject)
	{
		PVOID FsContext = FileObject->FsContext;

		AcquirePushLockShared(&_lock);

		PLIST_ENTRY head = this, entry = head;

		while ((entry = entry->Flink) != head)
		{
			PDO* pdo = static_cast<PDO*>(entry);

			if (FsContext == pdo)
			{
				pdo->_RemovePending = TRUE;
				break;
			}
		}

		ReleasePushLockShared(&_lock);

		if (entry != head)
		{
			DbgPrint("InvalidateDeviceRelations(pdo = %p)\n", FsContext);
			IoInvalidateDeviceRelations(_nextDeviceObject, BusRelations);
		}
	}

	return STATUS_SUCCESS;
}

NTSTATUS FDO::Create(PDEVICE_OBJECT DeviceObject, PIRP Irp, PIO_STACK_LOCATION IrpSp)
{
	PFILE_OBJECT FileObject = IrpSp->FileObject;

	DbgPrint("file <%wZ>\n", &FileObject->FileName);

	if (!FileObject->FileName.Length) return STATUS_OBJECT_NAME_INVALID;

	NTSTATUS status;

	if (0 <= (status = IoCreateDevice(DeviceObject->DriverObject, sizeof(PDO), 
		0, FILE_DEVICE_SMARTCARD, FILE_REMOVABLE_MEDIA|FILE_AUTOGENERATED_DEVICE_NAME, FALSE, &DeviceObject))) 
	{
		PDO* pdo = new(DeviceObject) PDO(DeviceObject);

		FileObject->FsContext = pdo;

		AcquirePushLockExclusive(&_lock);
		
		ObfReferenceObject(pdo);
		InsertHeadList(this, pdo);

		ReleasePushLockExclusive(&_lock);

		IoInvalidateDeviceRelations(_nextDeviceObject, BusRelations);
		Irp->IoStatus.Information = FILE_CREATED;
		return STATUS_SUCCESS;
	}

	return status;
}

void free(PDEVICE_RELATIONS p)
{
	if (p)
	{
		DbgPrint("!!!!!!!!!!!!! got not empty PDEVICE_RELATIONS(%p) !!!!!!!!!!!!!\n", p);

		if (DWORD n = p->Count)
		{
			DbgPrint("!!!!!!!!!!!!! got not empty PDEVICE_RELATIONS(%p,u) !!!!!!!!!!!!!\n", p, n);

			PDEVICE_OBJECT* Objects = p->Objects, DeviceObject;
			do 
			{
				DeviceObject = *Objects++;
				DbgPrint("  %p %wZ\n", DeviceObject, &DeviceObject->DriverObject->DriverName);
				ObfDereferenceObject(DeviceObject);
			} while (--n);
		}

		ExFreePool(p);
	}
}

NTSTATUS OnComplete(PDEVICE_OBJECT DeviceObject, PIRP Irp, FDO* fdo)
{
	if (Irp->PendingReturned)
	{
		IoMarkIrpPending(Irp);
	}

	ExReleaseRundownProtection(fdo);

	return STATUS_SUCCESS;
}

NTSTATUS FDO::Power(PDEVICE_OBJECT DeviceObject, PIRP Irp, PIO_STACK_LOCATION IrpSp)
{
	if (!ExAcquireRundownProtection(this))
	{
		Irp->IoStatus.Status = STATUS_NO_SUCH_DEVICE;
		Irp->IoStatus.Information = 0;
		IofCompleteRequest(Irp, IO_NO_INCREMENT);
		return STATUS_NO_SUCH_DEVICE;
	}

	PIO_STACK_LOCATION nextIrpSp;
	*(nextIrpSp = IrpSp - 1) = *IrpSp;
	nextIrpSp->Control = SL_INVOKE_ON_SUCCESS|SL_INVOKE_ON_ERROR|SL_INVOKE_ON_CANCEL;
	nextIrpSp->Context = this;
	nextIrpSp->CompletionRoutine = (PIO_COMPLETION_ROUTINE)OnComplete;
	return PoCallDriver(_nextDeviceObject, Irp);
}

